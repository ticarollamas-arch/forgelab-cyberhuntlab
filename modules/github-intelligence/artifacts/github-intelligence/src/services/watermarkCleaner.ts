import { WatermarkSlopFinding } from '../types';

export interface CleanupResult {
  cleanedText: string;
  findings: WatermarkSlopFinding[];
  hasModifications: boolean;
}

const WATERMARK_PATTERNS = [
  {
    regex: /<!--\s*Generated with [a-zA-Z0-9_\- ]+\s*-->/gi,
    description: 'Comentário de geração automática de scaffolding descartável',
    isMandatory: false,
  },
  {
    regex: /\[!\[Generated by [^\]]+\]\([^)]+\)\]\([^)]+\)/gi,
    description: 'Badge promocional de gerador automático de templates',
    isMandatory: false,
  },
  {
    regex: /Created with \u2764\ufe0f using [a-zA-Z0-9_\- ]+ Generator\.?/gi,
    description: 'Assinatura promocional genérica de gerador de código',
    isMandatory: false,
  },
  {
    regex: /This project was bootstrapped with \[Create React App\]\([^)]+\)\./gi,
    description: 'Texto padrão redundante do Create React App legado',
    isMandatory: false,
  },
  {
    regex: /## Getting Started\s*First, run the development server:\s*```bash[\s\S]*?npm run dev[\s\S]*?```\s*Open \[http:\/\/localhost:3000\][\s\S]*?Learn More[\s\S]*?Deploy on Vercel[\s\S]*?Check out our Next\.js deployment documentation/gi,
    description: 'Boilerplate genérico padrão de inicialização de template',
    isMandatory: false,
  },
  {
    regex: /<!-- TODO: Add project description here -->/gi,
    description: 'Comentário de placeholder esquecido',
    isMandatory: false,
  },
  {
    regex: /\[Insert project name here\]|\[Your Name\]|\[your-github-username\]/gi,
    description: 'Placeholders vazios não preenchidos de template',
    isMandatory: false,
  },
];

export function cleanWatermarksAndSlop(filePath: string, text: string): CleanupResult {
  const findings: WatermarkSlopFinding[] = [];
  let cleaned = text;

  const protectedAttributionPattern = /(copyright|©|licen[cs]e|licen[çc]a|attribution|author|autoria|cr[eé]dito|credit|trademark|marca registrada)/i;
  for (const item of WATERMARK_PATTERNS) {
    const matches = Array.from(cleaned.matchAll(item.regex));
    if (matches.length > 0) {
      const removableRanges: Array<{ start: number; end: number }> = [];
      for (const m of matches) {
        const start = m.index ?? 0;
        const lineStart = cleaned.lastIndexOf('\n', start - 1) + 1;
        const lineEndCandidate = cleaned.indexOf('\n', start);
        const lineEnd = lineEndCandidate === -1 ? cleaned.length : lineEndCandidate;
        const surroundingLine = cleaned.slice(lineStart, lineEnd);
        const protectedAttribution = item.isMandatory || protectedAttributionPattern.test(surroundingLine);
        findings.push({
          id: `slop-${findings.length + 1}`,
          filePath,
          patternDetected: m[0].slice(0, 50) + (m[0].length > 50 ? '...' : ''),
          description: protectedAttribution
            ? 'Aviso de autoria, atribuição ou licença preservado'
            : item.description,
          canSafelyRemove: !protectedAttribution,
          isMandatoryAttribution: protectedAttribution,
        });
        if (!protectedAttribution) removableRanges.push({ start, end: start + m[0].length });
      }
      // Remove only safe ranges, from the end to keep offsets stable.
      for (const range of removableRanges.sort((a, b) => b.start - a.start)) {
        cleaned = cleaned.slice(0, range.start) + cleaned.slice(range.end);
      }
    }
  }

  // Remove multiple trailing empty lines created by removals
  cleaned = cleaned.replace(/\n{3,}/g, '\n\n').trim() + '\n';

  return {
    cleanedText: cleaned,
    findings,
    hasModifications: cleaned !== text,
  };
}
